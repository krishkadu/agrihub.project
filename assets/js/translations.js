/* ═══════════════════════════════════════════════
   Reusable Translation Helper Functions
   ═══════════════════════════════════════════════ */

function getCurrentLanguage() {
  const saved = localStorage.getItem('agrihub_lang');
  if (saved && ['en', 'hi', 'mr'].includes(saved)) return saved;
  const htmlLang = document.documentElement.getAttribute('lang');
  if (htmlLang && ['en', 'hi', 'mr'].includes(htmlLang)) return htmlLang;
  return 'en';
}

function t(key, params, forcedLang) {
  const lang = forcedLang || getCurrentLanguage();
  let text = (translations[lang] && translations[lang][key]) ||
             (translations.en && translations.en[key]) ||
             key;

  if (params && typeof params === 'object') {
    Object.keys(params).forEach(k => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), params[k]);
    });
  }
  return text;
}

function applyTranslations(lang) {
  if (!lang || !['en', 'hi', 'mr'].includes(lang)) {
    lang = getCurrentLanguage();
  }

  // 1. Update document lang and persist
  document.documentElement.setAttribute('lang', lang);
  try {
    localStorage.setItem('agrihub_lang', lang);
  } catch (e) {
    console.warn('[AgriHub i18n] LocalStorage write blocked:', e);
  }

  // 2. Synchronize all language selectors on the page
  document.querySelectorAll('#languageSelector, .lang-select').forEach(sel => {
    if (sel.value !== lang) {
      sel.value = lang;
    }
  });

  // 3. Localize elements with [data-i18n]
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');

    // Save initial original HTML on first encounter
    if (!el.hasAttribute('data-i18n-original')) {
      el.setAttribute('data-i18n-original', el.innerHTML);
    }

    let translated = (translations[lang] && translations[lang][key]) ||
                     (translations.en && translations.en[key]);

    if (!translated) return;

    // Check if element has an icon child that must be preserved
    const icon = el.querySelector('svg, i[data-lucide], .ah-icon, .ah-icon-lg');
    if (icon) {
      const iconClone = icon.cloneNode(true);
      el.innerHTML = '';
      el.appendChild(iconClone);
      el.appendChild(document.createTextNode(' ' + translated));
    } else {
      el.innerHTML = translated;
    }
  });

  // 4. Localize placeholders with [data-i18n-placeholder]
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translated = (translations[lang] && translations[lang][key]) ||
                       (translations.en && translations.en[key]);
    if (translated) {
      el.setAttribute('placeholder', translated);
    }
  });

  // 5. Localize titles with [data-i18n-title]
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const translated = (translations[lang] && translations[lang][key]) ||
                       (translations.en && translations.en[key]);
    if (translated) {
      el.setAttribute('title', translated);
    }
  });

  // 6. Localize aria-labels with [data-i18n-aria]
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    const translated = (translations[lang] && translations[lang][key]) ||
                       (translations.en && translations.en[key]);
    if (translated) {
      el.setAttribute('aria-label', translated);
    }
  });

  // 7. Dispatch custom event for dynamic components to update
  window.dispatchEvent(new CustomEvent('agrihub:languageChanged', {
    detail: { lang: lang }
  }));

  // 8. Re-initialize Lucide icons if available
  if (window.lucide && typeof window.lucide.createIcons === 'function') {
    window.lucide.createIcons();
  }
}

// Global API
window.AgriHubI18n = {
  translations,
  t,
  getLang: getCurrentLanguage,
  getCurrentLanguage,
  setLang: applyTranslations,
  applyTranslations
};

// Auto-run on DOMContentLoaded if not already triggered
document.addEventListener('DOMContentLoaded', () => {
  const current = getCurrentLanguage();
  applyTranslations(current);
});
